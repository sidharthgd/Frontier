"""Synthetic agent sessions with prefix reuse, for training workloads.

    sessions = generate_sessions(AgentSessionParams(), seed=0)   # a _Sessions
    workload = sample_session_workload(sessions, num_requests=150, qps=1.0, seed=0)

Each session is simulated call by call, in the session-trace format of
frontier/trace_prep/common.py (block ids for prompt and output, chained), so
it is sampled and replayed exactly like the real traces (sessions.py,
closed loop, prefix caching):

- A session starts with one of num_system_prompts shared system prompts
  (system_tokens, the same ids for every session with that prompt) plus
  first-call user content (lognormal).
- Each later call either continues (its prompt is the previous prompt, the
  previous output and appended tool results: lognormal growth), re-sends
  the previous prompt without its output plus a few tokens (p_redo: retries,
  parallel calls), or restarts (p_restart: keeps a uniform fraction of the
  previous prompt, at least the system prompt, plus lognormal new content).
- Outputs, think times (from a call's completion to the next call) and calls
  per session are lognormal.
- A call whose prompt + output would pass compact_at compacts, as in
  common.compact_session: the context restarts as compact_to tokens (the
  system prompt plus a fresh summary) plus the call's new tokens.

Arrival and completion times are nominal (service time from
nominal_prefill_tokens_per_s and nominal_decode_s_per_token); they place
calls in the sampling window and give think time, which closed-loop replay
uses instead.

PRESETS hold parameters fitted to the rebuilt eval traces (median, spread
and tail of first prompts, growth, outputs, think time, calls per session,
and the mix of continuing, re-sent and restarting calls).
randomized_params(seed) draws every parameter from a range spanning both, so
each training episode has its own workload distribution (domain
randomization, like Vidur's synthetic workloads).

Session traces named "synthetic:<preset>" or "synthetic:random" are
generated by synthetic_session_trace (sessions.load_sessions).
"""

from __future__ import annotations

import dataclasses
from dataclasses import dataclass
from typing import Dict, Optional, Tuple

import numpy as np
import pandas as pd

from frontier.trace_prep.common import BLOCK_TOKENS, BlockRuns


@dataclass(frozen=True)
class AgentSessionParams:
    num_sessions: int = 400
    # shared system prompts
    system_tokens: int = 11_000
    num_system_prompts: int = 2
    # first call's own content: lognormal(log median, sigma) tokens
    first_user_median: float = 6_000.0
    first_user_sigma: float = 1.1
    # tokens a continuing call appends after the previous output
    growth_median: float = 300.0
    growth_sigma: float = 1.84
    # output tokens
    output_median: float = 240.0
    output_sigma: float = 1.4
    max_output: int = 16_384
    # call transitions (the rest continue)
    p_redo: float = 0.0
    redo_new_median: float = 10.0
    p_restart: float = 0.04
    restart_new_median: float = 20_000.0
    restart_new_sigma: float = 1.3
    # seconds from a call's completion to the next call
    think_median: float = 2.0
    think_sigma: float = 2.66
    max_think: float = 3_600.0
    # calls per session
    calls_median: float = 16.0
    calls_sigma: float = 1.8
    max_calls: int = 2_000
    # the model's context (as finalize_trace: compact at 120k to 16k)
    compact_at: int = 120_000
    compact_to: int = 16_384
    # nominal service time, for placing calls in time only
    nominal_prefill_tokens_per_s: float = 10_000.0
    nominal_decode_s_per_token: float = 0.025


PRESETS: Dict[str, AgentSessionParams] = {
    # tracelab_coding_128k.csv: first prompt p50 17.7k / p90 35.5k, growth
    # log-mean 5.7 sd 1.84, output 5.48 / 1.41, think p50 2.0 s / p90 60 s,
    # calls/session p50 16 / mean 83, continue 92%, restart 3.8%
    "tracelab": AgentSessionParams(),
    # freeinference_2026-08-30_128k.csv: first prompt p50 27k (wide), growth
    # 4.78 / 2.13, output 5.68 / 1.09, think p50 2.1 s / p90 41 s,
    # calls/session p50 35 / mean 93, continue 83%, re-send without the
    # output 14% (~10 new tokens), restart ~1%
    "freeinference": AgentSessionParams(
        system_tokens=6_000,
        num_system_prompts=3,
        first_user_median=20_000.0,
        first_user_sigma=1.6,
        growth_median=120.0,
        growth_sigma=2.13,
        output_median=290.0,
        output_sigma=1.09,
        p_redo=0.14,
        p_restart=0.01,
        think_median=2.1,
        think_sigma=2.32,
        calls_median=35.0,
        calls_sigma=1.4,
    ),
}

# (low, high) per parameter for randomized_params; log-uniform for the ones
# in LOG_UNIFORM. They span both presets with margin.
RANDOM_RANGES: Dict[str, Tuple[float, float]] = {
    "system_tokens": (3_000, 16_000),
    "num_system_prompts": (1, 4),
    "first_user_median": (3_000, 30_000),
    "first_user_sigma": (0.7, 1.8),
    "growth_median": (60, 600),
    "growth_sigma": (1.4, 2.4),
    "output_median": (150, 450),
    "output_sigma": (0.9, 1.6),
    "p_redo": (0.0, 0.2),
    "p_restart": (0.005, 0.06),
    "restart_new_median": (5_000, 40_000),
    "think_median": (0.7, 6.0),
    "think_sigma": (1.8, 3.0),
    "calls_median": (10, 50),
    "calls_sigma": (1.2, 2.0),
}
LOG_UNIFORM = {
    "system_tokens", "first_user_median", "growth_median", "output_median",
    "restart_new_median", "think_median", "calls_median",
}
INTEGER = {"system_tokens", "num_system_prompts"}


def randomized_params(seed: int, base: Optional[AgentSessionParams] = None) -> AgentSessionParams:
    """Every RANDOM_RANGES parameter drawn independently for this seed."""
    rng = np.random.default_rng([seed, 0x5E55])
    values = {}
    for name, (low, high) in RANDOM_RANGES.items():
        if name in LOG_UNIFORM:
            value = float(np.exp(rng.uniform(np.log(low), np.log(high))))
        else:
            value = float(rng.uniform(low, high + (1 if name in INTEGER else 0)))
        values[name] = int(value) if name in INTEGER else value
    return dataclasses.replace(base or AgentSessionParams(), **values)


def _lognormal(rng, median: float, sigma: float) -> float:
    return float(median * np.exp(sigma * rng.standard_normal()))


class _Ids:
    def __init__(self) -> None:
        self.next = 0

    def take(self, runs: BlockRuns, n: int) -> None:
        if n > 0:
            runs.extend(self.next, n)
            self.next += n


def generate_session_frame(params: AgentSessionParams, seed: int) -> pd.DataFrame:
    """The sessions as a session trace frame (common.COLUMNS)."""
    p = params
    rng = np.random.default_rng([seed, 0xA6E7])
    ids = _Ids()
    system_blocks = max(p.system_tokens // BLOCK_TOKENS, 1)
    systems = []
    for _ in range(max(p.num_system_prompts, 1)):
        runs = BlockRuns()
        ids.take(runs, system_blocks)
        systems.append(runs)
    max_context = p.compact_at
    rows = {name: [] for name in (
        "arrived_at", "completed_at", "session_id", "step", "num_prefill_tokens",
        "num_decode_tokens", "block_hash_ids",
    )}
    for session in range(p.num_sessions):
        system = systems[int(rng.integers(len(systems)))]
        num_calls = int(min(max(round(_lognormal(rng, p.calls_median, p.calls_sigma)), 1), p.max_calls))
        clock = 0.0
        previous: Optional[Tuple[int, int, BlockRuns]] = None  # prompt, output, ids
        for step in range(num_calls):
            output = int(min(max(round(_lognormal(rng, p.output_median, p.output_sigma)), 1), p.max_output))
            if previous is None:
                keep_tokens, keep_runs = system.num_blocks * BLOCK_TOKENS, system
                new = _lognormal(rng, p.first_user_median, p.first_user_sigma)
            else:
                prompt0, output0, seq0 = previous
                draw = rng.random()
                if draw < p.p_restart:
                    keep_tokens = max(int(rng.random() * prompt0), system.num_blocks * BLOCK_TOKENS)
                    keep_tokens = min(keep_tokens, prompt0)
                    keep_runs = seq0
                    new = _lognormal(rng, p.restart_new_median, p.restart_new_sigma)
                elif draw < p.p_restart + p.p_redo:
                    keep_tokens, keep_runs = prompt0, seq0
                    new = _lognormal(rng, p.redo_new_median, 1.0)
                else:
                    keep_tokens, keep_runs = prompt0 + output0, seq0
                    new = _lognormal(rng, p.growth_median, p.growth_sigma)
            new = int(max(round(new), 1))
            prompt = keep_tokens + new
            runs = keep_runs.prefix(keep_tokens // BLOCK_TOKENS)
            if prompt + output > max_context:
                # compact: system prompt, fresh summary, then what fits of the new tokens
                summary = max(p.compact_to - system.num_blocks * BLOCK_TOKENS, 0)
                new = min(new, max_context - output - system.num_blocks * BLOCK_TOKENS - summary)
                if new < 1:
                    output = max(max_context - p.compact_to - 1, 1)
                    new = 1
                prompt = system.num_blocks * BLOCK_TOKENS + summary + new
                runs = system.prefix(system.num_blocks)
                keep_tokens = system.num_blocks * BLOCK_TOKENS
            ids.take(runs, prompt // BLOCK_TOKENS - runs.num_blocks)
            ids.take(runs, (prompt + output) // BLOCK_TOKENS - prompt // BLOCK_TOKENS)
            uncached = prompt - keep_tokens if previous is not None else prompt
            service = uncached / p.nominal_prefill_tokens_per_s + output * p.nominal_decode_s_per_token
            if previous is not None:
                clock += min(_lognormal(rng, p.think_median, p.think_sigma), p.max_think)
            rows["arrived_at"].append(clock)
            clock += service
            rows["completed_at"].append(clock)
            rows["session_id"].append(session)
            rows["step"].append(step)
            rows["num_prefill_tokens"].append(prompt)
            rows["num_decode_tokens"].append(output)
            rows["block_hash_ids"].append(runs)
            previous = (prompt, output, runs)
    frame = pd.DataFrame(rows)
    frame["block_hash_ids"] = [r.encode() for r in frame["block_hash_ids"]]
    frame["ids_cover_output"] = 1
    return frame


def synthetic_params(name: str, seed: int) -> Tuple[AgentSessionParams, float]:
    """Parameters for "synthetic:<preset>" or "synthetic:random", and the
    load multiplier: random also draws the offered load (qps) from 0.5x to
    2x the workload's, log-uniform."""
    kind = name.split(":", 1)[1] if ":" in name else "random"
    if kind == "random":
        rng = np.random.default_rng([seed, 0x10AD])
        return randomized_params(seed), float(np.exp(rng.uniform(np.log(0.5), np.log(2.0))))
    if kind not in PRESETS:
        raise ValueError(f"unknown synthetic preset {kind!r}: {sorted(PRESETS)} or random")
    return PRESETS[kind], 1.0


def is_synthetic(name: Optional[str]) -> bool:
    return bool(name) and str(name).startswith("synthetic")
