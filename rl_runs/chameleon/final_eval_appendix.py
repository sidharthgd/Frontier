"""Appendix tables for RESULTS.md: TTFT and e2e p50/p95/p99/p100 (seconds) for
every policy on every eval workload, pooled over the 18 seeds of
final_eval18/requests.csv, plus the change vs FCFS at p95 with a paired
seed-bootstrap 90% interval (the analysis in final_eval_analysis.py stops at
p99).

    .venv/bin/python rl_runs/chameleon/final_eval_appendix.py
writes final_eval18/appendix.md and final_eval18/quantiles.csv.
"""
import os

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(ROOT, "final_eval18")
W = ["tracelab_c10", "freeinference_c10", "tracelab_c8", "freeinference_c8"]
SHORT = {"tracelab_c8": "TraceLab c8", "freeinference_c8": "FreeInference c8",
         "tracelab_c10": "TraceLab c10", "freeinference_c10": "FreeInference c10"}
BASE = {"fcfs": "FCFS", "sjf_prefill_tokens": "plain SJF",
        "sjf_prefill_tokens_age200": "age200", "sjf_prefill_tokens_rel30": "rel30"}
RUN = {"imitation": "imitation", "ppo_w0.01": "imit+PPO h0.01", "ppo_w0.02": "imit+PPO h0.02",
       "ppo_w0.04": "imit+PPO h0.04", "ppo_w0.01_lr3e-5": "imit+PPO h0.01 lr3e-5",
       "ppo_w0.02_lr3e-5": "imit+PPO h0.02 lr3e-5", "ppo_imit_e2e_w2": "imit+PPO e2e+2h",
       "ppo_pure_e2e_w1": "pure e2e+1h", "ppo_pure_e2e_w1_seed1": "pure e2e+1h s1",
       "ppo_pure_e2e_w2": "pure e2e+2h", "ppo_pure_e2e_w6": "pure e2e+6h",
       "ppo_pure_e2e_sq0.01": "pure e2e+0.01sq", "ppo_pure_e2e_sq0.02": "pure e2e+0.02sq",
       "ppo_pure_e2e_sq0.05": "pure e2e+0.05sq"}
Q = [0.5, 0.95, 0.99, 1.0]
iters = {}
for line in open(os.path.join(D, "checkpoint_iterations.txt")):
    path, it, _ = line.split()
    iters[path] = int(it)


def label(policy):
    if policy in BASE:
        return BASE[policy], "baseline"
    path = policy[len("ckpt:"):]
    run, f = path.split("/")[-2:]
    if f == "cdfs_iter10.pt":
        return f"{RUN[run]} @10", "other"
    return f"{RUN[run]} @{iters.get(path, '?')}", f[:-3]


src = os.path.join(D, "requests.csv")
d = pd.read_csv(src if os.path.exists(src) else src + ".gz",
                usecols=["workload", "seed", "policy", "ttft", "e2e"])
seeds = np.sort(d.seed.unique())
rng = np.random.default_rng(0)
boot = rng.integers(0, len(seeds), size=(1000, len(seeds)))
groups = {k: g for k, g in d.groupby(["workload", "policy"])}


def per_seed(g, col):
    by = dict(tuple(g.groupby("seed")[col]))
    return [by[s].to_numpy() for s in seeds]


def interval(a_seed, r_seed, q):
    out = [np.quantile(np.concatenate([a_seed[i] for i in idx]), q)
           / np.quantile(np.concatenate([r_seed[i] for i in idx]), q) - 1 for idx in boot]
    return np.quantile(out, [0.05, 0.95])


rows = []
for w in W:
    f = groups[(w, "fcfs")]
    f_e2e, f_ttft = per_seed(f, "e2e"), per_seed(f, "ttft")
    for policy in d.policy.unique():
        g = groups[(w, policy)]
        name, kind = label(policy)
        row = dict(workload=w, policy=policy, label=name, kind=kind)
        for col in ("ttft", "e2e"):
            for q in Q:
                row[f"{col}_p{int(q * 100)}"] = g[col].quantile(q)
            row[f"{col}_mean"] = g[col].mean()
        if policy != "fcfs":
            lo, hi = interval(per_seed(g, "e2e"), f_e2e, 0.95)
            row.update(e2e_d95_lo=lo, e2e_d95_hi=hi)
            lo, hi = interval(per_seed(g, "ttft"), f_ttft, 0.95)
            row.update(ttft_d95_lo=lo, ttft_d95_hi=hi)
        rows.append(row)
s = pd.DataFrame(rows)
for col in ("ttft", "e2e"):
    for q in ("p50", "p95", "p99", "p100", "mean"):
        ref = s.workload.map(s[s.policy == "fcfs"].set_index("workload")[f"{col}_{q}"])
        s[f"{col}_d{q[1:] if q != 'mean' else 'mean'}"] = s[f"{col}_{q}"] / ref - 1
s.to_csv(os.path.join(D, "quantiles.csv"), index=False)

KIND_ORDER = {"baseline": 0, "best": 1, "latest": 2, "other": 3}
s["_k"] = s.kind.map(KIND_ORDER)
out = ["# Appendix: TTFT and e2e quantiles, every policy (18 seeds)", "",
       "Seconds, pooled over the scored calls of 18 eval seeds (5,400 calls per policy at c10, "
       "5,472 at c8). Percentages are the change vs FCFS on the same workload, computed from unrounded values. Each column shows 3 significant figures of FCFS's value, or more where needed so that a nonzero change never sits next to a value that reads the same as FCFS's. `best` is the "
       "checkpoint each run selected on its eval reward, `latest` the last one trained; @N is "
       "the training iteration. Generated by `final_eval_appendix.py` from "
       "`final_eval18/requests.csv.gz`.", ""]


def decimals(z, column):
    """Decimals for one column of one workload's table: 3 significant figures of
    FCFS's value, more if needed so that every value whose change vs FCFS shows
    as nonzero (one decimal, in %) also reads differently from FCFS's value."""
    ref = z.loc[z.policy == "fcfs", column].iloc[0]
    d = max(0, 2 - int(np.floor(np.log10(abs(ref))))) if ref else 2
    changed = z.loc[(z.policy != "fcfs") & (abs(z[column] / ref - 1) >= 0.0005), column]
    while d < 4 and any(round(v, d) == round(ref, d) for v in changed):
        d += 1
    return d


def pc(x):
    """A change in %, one decimal, without a -0.0%."""
    return f"{100 * x + 0.0:+.1f}%" if round(100 * x, 1) != 0 else "+0.0%"


def cell(r, col, q, d):
    v = r[f"{col}_p{q}"]
    if r.policy == "fcfs":
        return f"{v:,.{d}f}"
    return f"{v:,.{d}f} ({pc(r[f'{col}_d{q}'])})"


for w in W:
    z = s[s.workload == w].sort_values(["_k", "label"])
    out += [f"## {SHORT[w]}", "",
            "| policy | ckpt | TTFT p50 | TTFT p95 | TTFT p99 | TTFT p100 | e2e p50 | e2e p95 | e2e p99 | e2e p100 |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    dec = {(c, q): decimals(z, f"{c}_p{q}") for c in ("ttft", "e2e") for q in ("50", "95", "99", "100")}
    for r in z.to_dict("records"):
        kind = "" if r["kind"] == "baseline" else r["kind"]
        r = pd.Series(r)
        out.append(f"| {r.label} | {kind} | " + " | ".join(
            cell(r, c, q, dec[(c, q)]) for c in ("ttft", "e2e") for q in ("50", "95", "99", "100")) + " |")
    out.append("")

key = ["FCFS", "plain SJF", "age200", "rel30"]
out += ["## e2e and TTFT p95 change vs FCFS with 90% seed-bootstrap intervals (key policies)", "",
        "| workload | policy | e2e p95 | change [90%] | TTFT p95 | change [90%] |", "|---|---|---|---|---|---|"]
for w in W:
    z = s[(s.workload == w) & ((s.label.isin(key)) | (s.kind == "best"))
          & s.label.str.match(r"(plain SJF|age200|rel30|pure e2e\+1h|pure e2e\+0\.02sq)")]
    ww = s[s.workload == w]
    de, dt = decimals(ww, "e2e_p95"), decimals(ww, "ttft_p95")
    for r in z.sort_values(["_k", "label"]).itertuples():
        out.append(f"| {SHORT[w]} | {r.label} {'' if r.kind == 'baseline' else r.kind} | "
                   f"{r.e2e_p95:,.{de}f} | {pc(r.e2e_d95)} [{100 * r.e2e_d95_lo:+.1f}, {100 * r.e2e_d95_hi:+.1f}] | "
                   f"{r.ttft_p95:,.{dt}f} | {pc(r.ttft_d95)} [{100 * r.ttft_d95_lo:+.1f}, {100 * r.ttft_d95_hi:+.1f}] |")
open(os.path.join(D, "appendix.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out[-25:]))
